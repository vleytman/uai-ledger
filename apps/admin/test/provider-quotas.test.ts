// @vitest-environment jsdom
import {createElement} from 'react';
import {afterEach,beforeEach,test,expect,vi} from 'vitest';
import {cleanup,render,screen,fireEvent,waitFor} from '@testing-library/react';
import {ProviderQuotas,type QuotaGroup} from '../../../packages/admin-module/src/components/provider-quotas';
import * as client from '../../../packages/admin-module/src/client';
const group:QuotaGroup={id:'quota-a',name:'Text quota',provider:'fake',source:'Synthetic source',checked_at:'2026-09-19T12:00:00Z',settings_revision:3,rules_revision:7,concurrency_limit:8,held_slots:2,blocked_until:null,rules:[{key:'rpm',metric:'requests',capacity:'100',window_ms:60000}],bindings:[{connection_id:'connection',connection_name:'Test connection',model:'gpt-4.1'}]};
beforeEach(()=>{vi.spyOn(client,'api').mockImplementation(async(_view,id)=>({group_id:id,rules_revision:7,status:'not_configured',sampled_at:null,rules:[]}))});
afterEach(()=>{cleanup();vi.restoreAllMocks()});
test('saves settings with a separate revision and preserves failed edits for an idempotent retry',async()=>{
 const command=vi.spyOn(client,'command').mockRejectedValueOnce(new Error('Connection lost')).mockResolvedValueOnce({...group,settings_revision:4,concurrency_limit:12});
 const onSaved=vi.fn();render(createElement(ProviderQuotas,{groups:[group],onSaved}));
 expect(screen.getByRole('table',{name:'Provider quota rules'})).toBeTruthy();expect(screen.getByText('GPT-4.1')).toBeTruthy();
 fireEvent.click(screen.getByRole('button',{name:'Edit group settings'}));
 fireEvent.change(screen.getByLabelText('Concurrent calls'),{target:{value:'12'}});
 fireEvent.change(screen.getByLabelText('Quota change reason'),{target:{value:'Raise concurrency'}});
 fireEvent.click(screen.getByRole('button',{name:'Save group settings'}));
 expect((await screen.findByRole('alert')).textContent).toContain('Connection lost');
 expect((screen.getByLabelText('Concurrent calls') as HTMLInputElement).value).toBe('12');
 fireEvent.click(screen.getByRole('button',{name:'Save group settings'}));await waitFor(()=>expect(onSaved).toHaveBeenCalledOnce());
 expect(command.mock.calls[0]).toEqual(command.mock.calls[1]);
 expect(command.mock.calls[0]).toEqual(['quota_settings_update',{settings_revision:3,settings:{name:group.name,source:group.source,checked_at:group.checked_at,concurrency_limit:12,interactive_reserve:1},reason:'Raise concurrency'},expect.any(String),'quota-a']);
});
